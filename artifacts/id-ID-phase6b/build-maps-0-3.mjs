import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function load(name) {
  return JSON.parse(fs.readFileSync(path.join(__dirname, name), "utf8"));
}

function writeMap(chunkIndex, idArr) {
  const en = load(`strings-chunk-${chunkIndex}.json`);
  if (en.length !== idArr.length) {
    throw new Error(
      `chunk ${chunkIndex}: length mismatch en=${en.length} id=${idArr.length}`
    );
  }
  const map = {};
  for (let i = 0; i < en.length; i++) {
    const k = en[i];
    const v = idArr[i];
    if (typeof v !== "string" || !v.trim()) {
      throw new Error(`chunk ${chunkIndex} empty at ${i}: ${JSON.stringify(k)}`);
    }
    if (Object.prototype.hasOwnProperty.call(map, k)) {
      throw new Error(`chunk ${chunkIndex} duplicate key at ${i}`);
    }
    map[k] = v;
  }
  const out = path.join(__dirname, `map-chunk-${chunkIndex}.json`);
  fs.writeFileSync(out, JSON.stringify(map, null, 2) + "\n", "utf8");
  console.log(`Wrote ${out} keys=${Object.keys(map).length}`);
}

