import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function load(n) {
  return JSON.parse(fs.readFileSync(path.join(__dirname, `strings-chunk-${n}.json`), "utf8"));
}

function writeMap(n, translations) {
  const keys = load(n);
  if (keys.length !== translations.length) {
    throw new Error(`chunk ${n}: expected ${keys.length} translations, got ${translations.length}`);
  }
  const map = {};
  for (let i = 0; i < keys.length; i++) {
    map[keys[i]] = translations[i];
  }
  const out = path.join(__dirname, `map-chunk-${n}.json`);
  fs.writeFileSync(out, JSON.stringify(map, null, 2) + "\n", "utf8");
  console.log(`Wrote ${out} keys=${Object.keys(map).length}`);
}

