const dict = {};
const missing = [];
let translated = 0;
let retainedEnglishLearning = 0;

for (const key of strings) {
  if (RETAIN.has(key)) {
    dict[key] = key;
    retainedEnglishLearning++;
  } else if (Object.prototype.hasOwnProperty.call(T, key)) {
    dict[key] = T[key];
    translated++;
  } else {
    missing.push(key);
  }
}

const extraT = Object.keys(T).filter((k) => !strings.includes(k));
const extraRetain = [...RETAIN].filter((k) => !strings.includes(k));

if (missing.length || extraT.length || extraRetain.length) {
  console.error("MISSING translations:", missing.length);
  missing.forEach((m) => console.error("  -", JSON.stringify(m)));
  console.error("EXTRA in T (not in source):", extraT.length);
  extraT.forEach((m) => console.error("  +", JSON.stringify(m)));
  console.error("EXTRA in RETAIN (not in source):", extraRetain.length);
  extraRetain.forEach((m) => console.error("  +", JSON.stringify(m)));
  process.exit(1);
}

