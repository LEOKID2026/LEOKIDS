function escapeRegExp(s) {
  return String(s).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function isUnsafeShortPhrase(en) {
  // Mid-sentence noun/adjective swaps create EN/DE salad. Prefer full-line residue map.
  return String(en).length < 28;
}

function isPrefixSafePhrase(en) {
  // Only sentence-leading instructional stems may be applied partially.
  return /^(Today|Now you|In practice|We will|Here we|What |How |When you|Look |Try |Important|Example|Step |On the next|Let's |Scientific)/i.test(
    String(en)
  );
}

export function translateBookLineDe(line) {
  const raw = String(line ?? "");
  if (!raw.trim()) return raw;
  const trimmed = raw.trim();
  if (Object.prototype.hasOwnProperty.call(EXACT, trimmed)) {
    return raw.replace(trimmed, EXACT[trimmed]);
  }
  let out = raw;
  // Full-line / long EXACT substrings only (avoid "square"→"Quadrat" salad)
  for (const [en, de] of Object.entries(EXACT)) {
    if (isUnsafeShortPhrase(en)) continue;
    if (out.includes(en)) out = out.split(en).join(de);
  }
  for (const [en, de] of PHRASES) {
    if (isUnsafeShortPhrase(en) && !isPrefixSafePhrase(en)) continue;
    if (!isPrefixSafePhrase(en) && isUnsafeShortPhrase(en)) continue;
    // Non-prefix phrases must be long enough to be unambiguous educational stems
    if (!isPrefixSafePhrase(en) && String(en).length < 40) continue;
    if (!out.toLowerCase().includes(en.toLowerCase())) continue;
    // Prefix phrases: only replace at line start (after optional markdown bullets)
    if (isPrefixSafePhrase(en)) {
      const re = new RegExp(`^([\\s>*#-]*)(${escapeRegExp(en)})`, "i");
      if (!re.test(out)) continue;
      out = out.replace(re, (_, lead) => `${lead}${de}`);
      continue;
    }
    out = out.split(new RegExp(escapeRegExp(en), "gi")).join(de);
  }
  out = out
    .replace(/\bGrade\s*([1-6])\b/g, "$1. Klasse")
    .replace(/\bgrades\s*([1-6])\s*[–-]\s*([1-6])\b/gi, "Klassen $1–$2")
    .replace(/\bshekels?\b/gi, "Euro")
    .replace(/\bdollars?\b/gi, "Euro")
    .replace(/\$(\d)/g, "€$1")
    .replace(/\bJänner\b/g, "Januar")
    .replace(/\bSpital\b/g, "Krankenhaus")
    .replace(/\bVelo\b/g, "Fahrrad")
    .replace(/\bStudent\b/g, "Schülerin oder Schüler")
    .replace(/\bstudent\b/g, "Schülerin oder Schüler")
    .replace(/\bStudents\b/g, "Schülerinnen und Schüler")
    .replace(/\bstudents\b/g, "Schülerinnen und Schüler")
    .replace(/\bWorksheet\b/g, "Arbeitsblatt")
    .replace(/\bWorksheets\b/g, "Arbeitsblätter")
    .replace(/\bTeenagerbereich\b/g, "Zehnerplus-Bereich")
    .replace(/\badolescentes?\b/gi, "Zehnerplus");

  // Finish hybrid leftovers after long German stems (safe noun/phrase tails only)
  const looksGerman =
    /[äöüÄÖÜß]|\b(Heute|Jetzt|lernen|Geometrie|Mathematik|Naturwissenschaften|Übung|Inhaltsumfang|Quadrat|Rechteck|Dreieck|Zahlenstrahl)\b/.test(
      out
    );
  if (looksGerman) {
    const tails = [
      ["the rectangle", "das Rechteck"],
      ["the square", "das Quadrat"],
      ["the triangle", "das Dreieck"],
      ["the circle", "den Kreis"],
      ["the difference between", "den Unterschied zwischen"],
      ["the names of", "die Namen von"],
      ["parallel lines and", "parallele Geraden und"],
      ["rotation in the plane", "Drehung in der Ebene"],
      ["shapes that", "Formen, die"],
      ["number line", "Zahlenstrahl"],
      ["In practice,", "In der Übung"],
      ["In practice ", "In der Übung "],
      ["How many rows?", "Wie viele Zeilen?"],
      ["A square with a side of", "Ein Quadrat mit Seitenlänge"],
      ["fill in small squares and count!", "fülle kleine Quadrate aus und zähle!"],
      ["Example: the corner of a room — two walls.", "Beispiel: die Ecke eines Zimmers — zwei Wände."],
      ["- The angle of rotation:", "- Der Drehwinkel:"],
      ["the diagonal of a rectangle", "die Diagonale eines Rechtecks"],
      ["the diagonal of a square", "die Diagonale eines Quadrats"],
      ["angles in a triangle", "Winkel in einem Dreieck"],
      ["angles in a square", "Winkel in einem Quadrat"],
      ["in geometry.", "in Geometrie."],
      ["in geometry!", "in Geometrie!"],
      ["in science.", "in Naturwissenschaften."],
      ["in science!", "in Naturwissenschaften!"],
    ];
    for (const [en, de] of tails) {
      if (out.includes(en)) out = out.split(en).join(de);
    }
  }

  // Never ship prefix/partial salad: if English instructional residue remains, keep source
  // so residue-map full lines can win on the next authoring round.
  if (out !== raw && stillEnglishInstructional(out) && looksPartiallyEnglish(out)) {
    return raw;
  }
  return out;
}

function looksPartiallyEnglish(s) {
  return /\b(the|and|with|that|which|because|from|have|been|does|make|what|when|where|how|why|for|only|more|most|other|than|then|each|every|will|are|were|you|your|we|our|\bis\b|like|has|not|square|rectangle|triangle|geometry|science|diagonal|angle|angles|side|sides|formula|surface|space|light|number|line|quarter|turn|practice|questions|example|important|today|learn|find|tell|apart|using|units|perimeter|length|corner|to corner|measurements|forget|slanted|properties|name)\b/i.test(
    String(s || "")
  );
}

