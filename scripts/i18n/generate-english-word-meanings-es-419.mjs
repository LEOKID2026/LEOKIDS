function escapeJsString(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function main() {
  const missing = [];
  const extra = [];
  /** @type {Record<string, Record<string, string>>} */
  const out = {};

  for (const [listKey, list] of Object.entries(WORD_LISTS)) {
    const pack = DICT[listKey] || {};
    out[listKey] = {};
    for (const enWord of Object.keys(list)) {
      if (!(enWord in pack)) {
        missing.push(`${listKey}.${enWord}`);
        continue;
      }
      out[listKey][enWord] = pack[enWord];
    }
    for (const enWord of Object.keys(pack)) {
      if (!(enWord in list)) extra.push(`${listKey}.${enWord}`);
    }
  }

  for (const listKey of Object.keys(DICT)) {
    if (!(listKey in WORD_LISTS)) extra.push(`(category) ${listKey}`);
  }

  if (missing.length || extra.length) {
    console.error("Parity errors:");
    if (missing.length) console.error("  missing:", missing.join(", "));
    if (extra.length) console.error("  extra:", extra.join(", "));
    process.exit(1);
  }

  let total = 0;
  const lines = [
    "/**",
    " * Spanish (es-419 / LatAm neutral) meanings for English learning words.",
    " * Keys match WORD_LISTS English word IDs; values are child-friendly glosses.",
    " * Generated by scripts/i18n/generate-english-word-meanings-es-419.mjs — edit DICT there to regenerate.",
    " */",
    "",
    "export const WORD_MEANINGS_ES_419 = {",
  ];

  for (const [listKey, list] of Object.entries(out)) {
    lines.push(`  ${listKey}: {`);
    for (const [enWord, meaning] of Object.entries(list)) {
      lines.push(`    ${enWord}: "${escapeJsString(meaning)}",`);
      total += 1;
    }
    lines.push("  },");
  }
  lines.push("};");
  lines.push("");

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join("\n"), "utf8");
  console.log(`Wrote ${OUT} (${total} meanings)`);
}

main();
