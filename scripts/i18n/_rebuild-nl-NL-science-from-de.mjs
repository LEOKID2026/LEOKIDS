function isBad(s) {
  return STRICT.test(String(s || ""));
}

function recordBad(n) {
  if (!n) return true;
  return [n.stem, n.explanation, ...(n.options || []), ...(n.theoryLines || [])].some(isBad);
}

const enMod = await import(pathToFileURL(path.join(ROOT, "data/science-questions-en-overlay.js")).href + `?t=${Date.now()}`);
const deMod = await import(pathToFileURL(path.join(ROOT, "data/science-questions-de-DE-overlay.js")).href + `?t=${Date.now()}`);
const nlMod = await import(pathToFileURL(OUT).href + `?t=${Date.now()}`);
const EN = enMod.SCIENCE_EN_OVERLAY;
const DE = deMod.SCIENCE_DE_DE_OVERLAY;
const overlay = structuredClone(nlMod.SCIENCE_NL_NL_OVERLAY);

let rebuilt = 0;
for (const id of Object.keys(EN)) {
  if (!recordBad(overlay[id])) continue;
  const d = DE[id];
  if (!d) continue;
  overlay[id] = {
    stem: deToNl(d.stem),
    options: (d.options || []).map((o) => deToNl(o)),
    explanation: deToNl(d.explanation || ""),
    ...(Array.isArray(d.theoryLines) ? { theoryLines: d.theoryLines.map((t) => deToNl(t)) } : {}),
  };
  rebuilt++;
}

