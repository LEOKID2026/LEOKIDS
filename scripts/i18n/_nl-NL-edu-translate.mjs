function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function translateEduNl(en, { childFacing = true } = {}) {
  const raw = String(en ?? "");
  if (!raw.trim()) return raw;
  if (Object.prototype.hasOwnProperty.call(EXACT, raw)) return applyPost(EXACT[raw]);

  let out = raw;
  for (const [from, to] of PHRASES) {
    const re = new RegExp(`\\b${esc(from)}\\b`, "gi");
    out = out.replace(re, (m) => {
      if (m[0] === m[0].toUpperCase() && m !== m.toUpperCase()) {
        return to.charAt(0).toUpperCase() + to.slice(1);
      }
      return to;
    });
  }
  out = applyPost(out);
  if (!childFacing) {
    out = out
      .replace(/\bje\b/g, "u")
      .replace(/\bjouw\b/g, "uw")
      .replace(/\bJouw\b/g, "Uw")
      .replace(/\bJe\b/g, "U");
  }
  return out;
}

function applyPost(s) {
  let out = s;
  for (const [re, rep] of POST) out = out.replace(re, rep);
  return out.trim();
}

export function looksEnglishHeavy(s) {
  const str = String(s || "");
  if (!str.trim()) return false;
  const en = (str.match(/\b(the|what|which|because|survive|called|true|false|pulse|daytime|hypothesis|quickly|special|harmful|actually|automatically|growth|toward|cells|organs|jobs|learn about|how things)\b/gi) || []).length;
  return en >= 1;
}
