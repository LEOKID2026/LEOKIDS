function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function looksNonTranslate(s) {
  if (s == null) return true;
  const str = String(s);
  if (!str.trim()) return true;
  if (/^#([0-9a-f]{3}|[0-9a-f]{6}|[0-9a-f]{8})$/i.test(str)) return true;
  if (/^https?:\/\//i.test(str) || str.startsWith("mailto:")) return true;
  if (/^\{[a-zA-Z0-9_]+\}$/.test(str)) return true;
  if (/^\d+(\.\d+)?%?$/.test(str)) return true;
  if (/^[A-Z0-9_]{2,}$/.test(str) && str.length <= 48) return true;
  if (/[\u0590-\u05FF]/.test(str) && !/[A-Za-z]/.test(str)) return true;
  if (!/\s/.test(str)) {
    if (/^[a-z0-9]+([_/.-][a-z0-9]+)+$/i.test(str)) return true;
    if (/^[a-z]+[A-Z][a-zA-Z0-9]*$/.test(str)) return true;
    if (/^\/[a-z0-9/_\[\]-]+$/i.test(str)) return true;
    if (/\.(png|jpe?g|gif|webp|svg|ttf|woff2?|json|js|css|mp3|wav|pdf)$/i.test(str)) return true;
  }
  return false;
}

export function protectPlaceholders(s) {
  /** @type {string[]} */
  const ph = [];
  const out = String(s).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => {
    ph.push(name);
    return `⟦${ph.length - 1}⟧`;
  });
  return { text: out, ph };
}

export function restorePlaceholders(s, ph) {
  return String(s).replace(/⟦\s*(\d+)\s*⟧/g, (_, i) => `{${ph[Number(i)]}}`);
}

function applyPostFixes(text) {
  let out = text;
  for (const [re, rep] of POST_FIXES) out = out.replace(re, rep);
  for (const [enTerm, entry] of Object.entries(DUTCH_NETHERLANDS_GLOSSARY)) {
    if (!entry?.preferred || enTerm.length < 3) continue;
    const re = new RegExp(`\\b${escapeRegExp(enTerm)}\\b`, "g");
    out = out.replace(re, entry.preferred);
  }
  // Decimal comma for display-like decimals in prose (avoid changing IDs)
  out = out.replace(/\b(\d+)\.(\d+)\b/g, "$1,$2");
  return out.replace(/\s{2,}/g, " ").trim();
}

/**
 * Translate one educational English string to Netherlands Dutch (local engine).
 * @param {string} en
 * @param {{ childFacing?: boolean }} [opts]
 */
export function translateEnToNl(en, opts = {}) {
  if (looksNonTranslate(en)) return en;
  if (Object.prototype.hasOwnProperty.call(EXACT_OVERRIDES, en)) {
    return applyPostFixes(EXACT_OVERRIDES[en]);
  }

  const { text, ph } = protectPlaceholders(en);
  let out = text;

  for (const [from, to] of PHRASE_PAIRS) {
    if (out.includes(from)) out = out.split(from).join(to);
  }

  // Token pass for residual English words (keep punctuation)
  out = out.replace(/[A-Za-z]+(?:'[A-Za-z]+)?/g, (word) => {
    if (word === "Leo" || word === "Kids") return word;
    const lower = word.toLowerCase();
    if (WORD_MAP[lower] != null) {
      const mapped = WORD_MAP[lower];
      if (word[0] === word[0].toUpperCase() && word !== word.toUpperCase()) {
        return mapped.charAt(0).toUpperCase() + mapped.slice(1);
      }
      if (word === word.toUpperCase() && word.length > 1) return mapped.toUpperCase();
      return mapped;
    }
    return word;
  });

  out = restorePlaceholders(out, ph);
  out = applyPostFixes(out);

  if (opts.childFacing) {
    out = out
      .replace(/\buw\b/g, "jouw")
      .replace(/\bUw\b/g, "Jouw")
      .replace(/\bu kunt\b/g, "je kunt")
      .replace(/\bU kunt\b/g, "Je kunt");
  }

  // Grade display helpers when template still has numeric grade token meaning
  for (const [k, v] of Object.entries(NL_NL_GRADE_DISPLAY)) {
    if (out === k) return v;
  }

  return out;
}

