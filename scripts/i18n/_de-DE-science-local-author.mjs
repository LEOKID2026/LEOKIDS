function protect(s) {
  const ph = [];
  let out = String(s).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => {
    const i = ph.length;
    ph.push(`{${name}}`);
    return `«PH${i}»`;
  });
  out = out.replace(/\bH₂O\b/g, "«H2O»").replace(/\bCO₂\b/g, "«CO2»");
  return { out, ph };
}

function restore(s, ph) {
  let out = s.replace(/«H2O»/g, "H₂O").replace(/«CO2»/g, "CO₂");
  out = out.replace(/«PH(\d+)»/g, (_, i) => ph[Number(i)] || "");
  return out;
}

function applyPhrases(s) {
  let out = s;
  const sorted = [...PHRASES].sort((a, b) => b[0].length - a[0].length);
  for (const [en, de] of sorted) out = out.split(en).join(de);
  return out;
}

function applyWords(s) {
  const keys = Object.keys(WORDS).sort((a, b) => b.length - a.length);
  let out = s;
  for (const k of keys) {
    const re = new RegExp(`\\b${k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "g");
    out = out.replace(re, WORDS[k]);
    const reCap = new RegExp(`\\b${k.charAt(0).toUpperCase()}${k.slice(1).replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "g");
    const de = WORDS[k];
    out = out.replace(reCap, de.charAt(0).toUpperCase() + de.slice(1));
  }
  return out;
}

function postFix(s) {
  return s
    .replace(/\bGrade\s*(\d)\b/g, "$1. Klasse")
    .replace(/\bdollars?\b/gi, "Euro")
    .replace(/\bJänner\b/g, "Januar")
    .replace(/\bSpital\b/g, "Krankenhaus")
    .replace(/\bVelo\b/g, "Fahrrad")
    .replace(/\b32°F \(0°C\)/g, "0 °C (32 °F)")
    .replace(/\b32°F\b/g, "0 °C")
    .replace(/\s+/g, " ")
    .replace(/\s+([,.!?;:])/g, "$1")
    .trim();
}

export function authorScienceDe(en, exact = {}) {
  if (exact[en]) return exact[en];
  if (en == null) return en;
  const str = String(en);
  if (!str.trim()) return str;
  if (/^[\d\s+\-−–—×÷=<>().,/π√%°CF]+$/.test(str)) return str;
  const { out: protectedStr, ph } = protect(str);
  let s = applyPhrases(protectedStr);
  s = applyWords(s);
  s = postFix(s);
  s = restore(s, ph);
  return s;
}

function englishResidue(s) {
  const hits = (String(s).match(/\b(the|and|with|that|which|what|into|about|their|have|are|was|were|will|would|could|should|without|because|while|through|between|from|this|these|those|than|then|also|only|more|most|other|over|under|after|before|during|against|around|being|been|does|did|don't|can't|won't|isn't|aren't)\b/gi) || []).length;
  return hits;
}

export function emitRemainingBatches() {
  // Trust only human batches 001-008 + authored topic pairs
  const exact = JSON.parse(fs.readFileSync(path.join(BATCH, "_pair-cache-human.json"), "utf8"));
  let fromCache = 0;
  let authored = 0;
  let residue = 0;
  for (let i = 9; i <= 36; i++) {
    const n = String(i).padStart(3, "0");
    const en = JSON.parse(fs.readFileSync(path.join(BATCH, `en-${n}.json`), "utf8"));
    const de = en.map((s) => {
      if (exact[s]) {
        fromCache++;
        return exact[s];
      }
      const t = authorScienceDe(s, exact);
      authored++;
      if (englishResidue(t) >= 2) residue++;
      exact[s] = t;
      return t;
    });
    fs.writeFileSync(path.join(BATCH, `de-${n}.json`), `${JSON.stringify(de, null, 2)}\n`, "utf8");
    console.log(`de-${n} len=${de.length}`);
  }
  console.log({ fromCache, authored, residue });
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  emitRemainingBatches();
}
