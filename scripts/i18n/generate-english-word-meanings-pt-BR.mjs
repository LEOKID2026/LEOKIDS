const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "../..");
const OUT = path.join(ROOT, "data/english-questions/word-meanings/pt-BR.js");
const CACHE_PATH = path.join(__dirname, "_mt-cache-pt-BR-meanings.json");

/** Curated BR meanings by English word ID (context-checked). */
