export function translateBookLineNl(line) {
  const raw = String(line ?? "");
  if (!raw.trim()) return raw;
  const trimmed = raw.trim();
  if (Object.prototype.hasOwnProperty.call(EXACT, trimmed)) {
    return raw.replace(trimmed, EXACT[trimmed]);
  }
  let out = raw;
  for (const [en, nl] of Object.entries(EXACT)) {
    if (out.includes(en)) out = out.split(en).join(nl);
  }
  for (const [en, nl] of PHRASES) {
    if (!out.toLowerCase().includes(en.toLowerCase())) continue;
    const parts = out.split(new RegExp(en.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "gi"));
    out = parts.join(nl);
  }
  return out
    .replace(/\bWiskunde\b/g, "Rekenen")
    .replace(/\bGrade\s*1\b/g, "Groep 3")
    .replace(/\bGrade\s*2\b/g, "Groep 4")
    .replace(/\bGrade\s*3\b/g, "Groep 5")
    .replace(/\bGrade\s*4\b/g, "Groep 6")
    .replace(/\bGrade\s*5\b/g, "Groep 7")
    .replace(/\bGrade\s*6\b/g, "Groep 8");
}

